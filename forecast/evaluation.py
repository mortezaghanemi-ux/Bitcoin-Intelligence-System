"""Bitcoin forecast evaluation engine."""

from __future__ import annotations

import math

from datetime import datetime, timedelta, timezone
from typing import Any, Iterable


BULLISH = "BULLISH"
BEARISH = "BEARISH"
NEUTRAL = "NEUTRAL"

VALID_DIRECTIONS = {
    BULLISH,
    BEARISH,
    NEUTRAL,
}

DEFAULT_NEUTRAL_THRESHOLD_PCT = 1.0
DEFAULT_LOG_EPSILON = 1e-15


class ForecastEvaluationError(ValueError):
    """Raised when forecast evaluation cannot be completed."""


def _parse_utc_timestamp(
    value: Any,
    field_name: str,
) -> datetime:
    """Parse a timezone-aware UTC timestamp."""

    if isinstance(value, datetime):
        timestamp = value

    elif isinstance(value, str) and value.strip():
        try:
            timestamp = datetime.fromisoformat(
                value.strip().replace("Z", "+00:00")
            )
        except (TypeError, ValueError, OverflowError) as exc:
            raise ForecastEvaluationError(
                f"Invalid timestamp: {field_name}."
            ) from exc

    else:
        raise ForecastEvaluationError(
            f"{field_name} must be a valid UTC timestamp."
        )

    if timestamp.tzinfo is None:
        raise ForecastEvaluationError(
            f"{field_name} must be timezone-aware."
        )

    try:
        offset = timestamp.utcoffset()
    except (ValueError, OverflowError) as exc:
        raise ForecastEvaluationError(
            f"Invalid timezone: {field_name}."
        ) from exc

    if offset != timedelta(0):
        raise ForecastEvaluationError(
            f"{field_name} must use UTC."
        )

    return timestamp.astimezone(timezone.utc)


def _normalize_evaluation_time(
    evaluation_time: datetime | None,
) -> datetime:
    """Return evaluation time in UTC."""

    if evaluation_time is None:
        return datetime.now(timezone.utc)

    return _parse_utc_timestamp(
        evaluation_time,
        "evaluation_time",
    )


def _validate_positive_number(
    value: Any,
    field_name: str,
) -> float:
    """Validate a finite positive numeric value."""

    if (
        isinstance(value, bool)
        or not isinstance(value, (int, float))
        or not math.isfinite(value)
        or value <= 0
    ):
        raise ForecastEvaluationError(
            f"{field_name} must be a finite positive number."
        )

    return float(value)


def _validate_neutral_threshold(
    threshold_pct: float,
) -> float:
    """Validate the neutral market movement threshold."""

    if (
        isinstance(threshold_pct, bool)
        or not isinstance(threshold_pct, (int, float))
        or not math.isfinite(threshold_pct)
        or threshold_pct < 0
        or threshold_pct >= 100
    ):
        raise ForecastEvaluationError(
            "neutral_threshold_pct must be between 0 and 100."
        )

    return float(threshold_pct)


def _validate_forecast(
    forecast: dict[str, Any],
) -> dict[str, Any]:
    """Validate a forecast generated by the Forecast Engine."""

    if not isinstance(forecast, dict):
        raise ForecastEvaluationError(
            "forecast must be a dictionary."
        )

    if forecast.get("status") != "SUCCESS":
        raise ForecastEvaluationError(
            "Only successful forecasts can be evaluated."
        )

    required_fields = (
        "forecast_id",
        "asset",
        "forecast_timestamp",
        "forecast_horizon",
        "market_price",
        "probabilities",
        "confidence_score",
    )

    missing = [
        field
        for field in required_fields
        if field not in forecast
    ]

    if missing:
        raise ForecastEvaluationError(
            "Forecast is missing required fields: "
            + ", ".join(missing)
        )

    forecast_id = forecast["forecast_id"]

    if (
        not isinstance(forecast_id, str)
        or not forecast_id.strip()
    ):
        raise ForecastEvaluationError(
            "forecast_id must be a non-empty string."
        )

    if forecast["asset"] != "BTC":
        raise ForecastEvaluationError(
            "This evaluator currently supports BTC forecasts only."
        )

    forecast_timestamp = _parse_utc_timestamp(
        forecast["forecast_timestamp"],
        "forecast_timestamp",
    )

    market_price = _validate_positive_number(
        forecast["market_price"],
        "market_price",
    )

    horizon = forecast["forecast_horizon"]

    if not isinstance(horizon, dict):
        raise ForecastEvaluationError(
            "forecast_horizon must be a dictionary."
        )

    required_horizon_fields = (
        "days",
        "start",
        "end",
    )

    if any(
        field not in horizon
        for field in required_horizon_fields
    ):
        raise ForecastEvaluationError(
            "Forecast horizon is incomplete."
        )

    horizon_days = horizon["days"]

    if (
        isinstance(horizon_days, bool)
        or not isinstance(horizon_days, int)
        or horizon_days <= 0
        or horizon_days > 365
    ):
        raise ForecastEvaluationError(
            "Forecast horizon days must be between 1 and 365."
        )

    horizon_start = _parse_utc_timestamp(
        horizon["start"],
        "forecast_horizon.start",
    )

    horizon_end = _parse_utc_timestamp(
        horizon["end"],
        "forecast_horizon.end",
    )

    if horizon_start != forecast_timestamp:
        raise ForecastEvaluationError(
            "Forecast horizon start does not match forecast timestamp."
        )

    if horizon_end != (
        horizon_start + timedelta(days=horizon_days)
    ):
        raise ForecastEvaluationError(
            "Forecast horizon end is inconsistent with its duration."
        )

    probabilities = forecast["probabilities"]

    if not isinstance(probabilities, dict):
        raise ForecastEvaluationError(
            "Forecast probabilities must be a dictionary."
        )

    if set(probabilities) != VALID_DIRECTIONS:
        raise ForecastEvaluationError(
            "Forecast must contain all three market probabilities."
        )

    normalized_probabilities = {}

    for direction in VALID_DIRECTIONS:
        value = probabilities[direction]

        if (
            isinstance(value, bool)
            or not isinstance(value, (int, float))
            or not math.isfinite(value)
            or value < 0
            or value > 100
        ):
            raise ForecastEvaluationError(
                f"Invalid probability for {direction}."
            )

        normalized_probabilities[direction] = (
            float(value) / 100.0
        )

    probability_total = sum(
        normalized_probabilities.values()
    )

    if not math.isclose(
        probability_total,
        1.0,
        rel_tol=0.0,
        abs_tol=0.0001,
    ):
        raise ForecastEvaluationError(
            "Forecast probabilities must total 100 percent."
        )

    confidence = forecast["confidence_score"]

    if (
        isinstance(confidence, bool)
        or not isinstance(confidence, (int, float))
        or not math.isfinite(confidence)
        or not 0 <= confidence <= 100
    ):
        raise ForecastEvaluationError(
            "confidence_score must be between 0 and 100."
        )

    return {
        "forecast_id": forecast_id,
        "forecast_timestamp": forecast_timestamp,
        "horizon_start": horizon_start,
        "horizon_end": horizon_end,
        "horizon_days": horizon_days,
        "market_price": market_price,
        "probabilities": normalized_probabilities,
        "confidence_score": float(confidence),
    }


def _classify_market_outcome(
    reference_price: float,
    outcome_price: float,
    neutral_threshold_pct: float,
) -> tuple[str, float]:
    """Classify the actual market direction."""

    percentage_change = (
        (outcome_price - reference_price)
        / reference_price
    ) * 100.0

    if percentage_change > neutral_threshold_pct:
        direction = BULLISH

    elif percentage_change < -neutral_threshold_pct:
        direction = BEARISH

    else:
        direction = NEUTRAL

    return direction, percentage_change


def _calculate_brier_score(
    probabilities: dict[str, float],
    actual_direction: str,
) -> float:
    """Calculate the multiclass Brier score.

    The score ranges from 0 to 2.
    Lower values indicate better probabilistic forecasts.
    """

    if actual_direction not in VALID_DIRECTIONS:
        raise ForecastEvaluationError(
            "Invalid actual market direction."
        )

    score = 0.0

    for direction in VALID_DIRECTIONS:
        observed = (
            1.0 if direction == actual_direction else 0.0
        )

        score += (
            probabilities[direction] - observed
        ) ** 2

    return score


def _calculate_log_loss(
    probabilities: dict[str, float],
    actual_direction: str,
    epsilon: float = DEFAULT_LOG_EPSILON,
) -> float:
    """Calculate multiclass logarithmic loss."""

    if actual_direction not in VALID_DIRECTIONS:
        raise ForecastEvaluationError(
            "Invalid actual market direction."
        )

    if (
        isinstance(epsilon, bool)
        or not isinstance(epsilon, (int, float))
        or not math.isfinite(epsilon)
        or not 0 < epsilon < 0.5
    ):
        raise ForecastEvaluationError(
            "epsilon must be between 0 and 0.5."
        )

    probability = probabilities[actual_direction]

    probability = max(
        float(epsilon),
        min(1.0, probability),
    )

    return -math.log(probability)


def _calculate_directional_accuracy(
    probabilities: dict[str, float],
    actual_direction: str,
) -> bool:
    """Check whether the highest-probability direction was correct."""

    predicted_direction = max(
        VALID_DIRECTIONS,
        key=lambda direction: (
            probabilities[direction],
            direction == NEUTRAL,
        ),
    )

    return predicted_direction == actual_direction


def evaluate_forecast(
    forecast: dict[str, Any],
    actual_market_data: dict[str, Any],
    evaluation_time: datetime | None = None,
    neutral_threshold_pct: float = DEFAULT_NEUTRAL_THRESHOLD_PCT,
) -> dict[str, Any]:
    """
    Evaluate one completed forecast against actual market data.

    actual_market_data must contain:
        outcome_price
        outcome_timestamp

    The outcome direction is calculated from the forecast's
    original market price and the actual outcome price.

    Evaluation is rejected before the forecast horizon ends.
    """

    current_time = _normalize_evaluation_time(
        evaluation_time
    )

    threshold = _validate_neutral_threshold(
        neutral_threshold_pct
    )

    validated = _validate_forecast(
        forecast
    )

    if current_time < validated["horizon_end"]:
        raise ForecastEvaluationError(
            "Forecast horizon has not completed."
        )

    if not isinstance(actual_market_data, dict):
        raise ForecastEvaluationError(
            "actual_market_data must be a dictionary."
        )

    required_actual_fields = (
        "outcome_price",
        "outcome_timestamp",
    )

    missing = [
        field
        for field in required_actual_fields
        if field not in actual_market_data
    ]

    if missing:
        raise ForecastEvaluationError(
            "Actual market data is missing fields: "
            + ", ".join(missing)
        )

    outcome_price = _validate_positive_number(
        actual_market_data["outcome_price"],
        "outcome_price",
    )

    outcome_timestamp = _parse_utc_timestamp(
        actual_market_data["outcome_timestamp"],
        "outcome_timestamp",
    )

    if outcome_timestamp < validated["horizon_end"]:
        raise ForecastEvaluationError(
            "Actual outcome timestamp is before forecast horizon completion."
        )

    if outcome_timestamp > current_time:
        raise ForecastEvaluationError(
            "Actual outcome timestamp cannot be in the future."
        )

    actual_direction, percentage_change = (
        _classify_market_outcome(
            reference_price=validated["market_price"],
            outcome_price=outcome_price,
            neutral_threshold_pct=threshold,
        )
    )

    probabilities = validated["probabilities"]

    brier_score = _calculate_brier_score(
        probabilities,
        actual_direction,
    )

    log_loss = _calculate_log_loss(
        probabilities,
        actual_direction,
    )

    directional_accuracy = _calculate_directional_accuracy(
        probabilities,
        actual_direction,
    )

    return {
        "evaluation_id": (
            f"{validated['forecast_id']}-EVALUATION"
        ),
        "forecast_id": validated["forecast_id"],
        "status": "SUCCESS",
        "evaluated_at": current_time.isoformat(),
        "forecast_timestamp": (
            validated["forecast_timestamp"].isoformat()
        ),
        "forecast_horizon_end": (
            validated["horizon_end"].isoformat()
        ),
        "actual_outcome": {
            "timestamp": outcome_timestamp.isoformat(),
            "reference_price": validated["market_price"],
            "outcome_price": outcome_price,
            "percentage_change": round(
                percentage_change,
                6,
            ),
            "direction": actual_direction,
            "neutral_threshold_pct": threshold,
        },
        "predicted_outcome": {
            "probabilities": probabilities,
            "predicted_direction": max(
                VALID_DIRECTIONS,
                key=lambda direction: (
                    probabilities[direction],
                    direction == NEUTRAL,
                ),
            ),
            "confidence_score": (
                validated["confidence_score"]
            ),
        },
        "metrics": {
            "brier_score": round(brier_score, 10),
            "log_loss": round(log_loss, 10),
            "directional_accuracy": (
                1.0 if directional_accuracy else 0.0
            ),
            "directional_correct": directional_accuracy,
        },
        "metadata": {
            "asset": "BTC",
            "horizon_days": validated["horizon_days"],
            "method": "multiclass_probability_evaluation",
            "statistical_calibration_assessed": False,
        },
    }


def evaluate_forecasts(
    evaluations: Iterable[dict[str, Any]],
) -> dict[str, Any]:
    """
    Aggregate completed forecast evaluation results.

    This function accepts only successful evaluation records.
    It does not modify the input records.
    """

    if isinstance(evaluations, (str, bytes, dict)):
        raise ForecastEvaluationError(
            "evaluations must be an iterable of evaluation records."
        )

    try:
        records = list(evaluations)
    except TypeError as exc:
        raise ForecastEvaluationError(
            "evaluations must be iterable."
        ) from exc

    if not records:
        raise ForecastEvaluationError(
            "At least one evaluation record is required."
        )

    seen_forecast_ids = set()

    brier_scores = []
    log_losses = []
    correct_predictions = []

    for record in records:

        if not isinstance(record, dict):
            raise ForecastEvaluationError(
                "Every evaluation record must be a dictionary."
            )

        if record.get("status") != "SUCCESS":
            raise ForecastEvaluationError(
                "Only successful evaluation records can be aggregated."
            )

        forecast_id = record.get("forecast_id")

        if (
            not isinstance(forecast_id, str)
            or not forecast_id.strip()
        ):
            raise ForecastEvaluationError(
                "Evaluation record has an invalid forecast_id."
            )

        if forecast_id in seen_forecast_ids:
            raise ForecastEvaluationError(
                "Duplicate forecast evaluations are not allowed."
            )

        seen_forecast_ids.add(forecast_id)

        metrics = record.get("metrics")

        if not isinstance(metrics, dict):
            raise ForecastEvaluationError(
                "Evaluation metrics must be a dictionary."
            )

        brier = metrics.get("brier_score")
        loss = metrics.get("log_loss")
        accuracy = metrics.get("directional_accuracy")

        for value, name in (
            (brier, "brier_score"),
            (loss, "log_loss"),
            (accuracy, "directional_accuracy"),
        ):
            if (
                isinstance(value, bool)
                or not isinstance(value, (int, float))
                or not math.isfinite(value)
            ):
                raise ForecastEvaluationError(
                    f"Invalid {name} in evaluation record."
                )

        if not 0 <= brier <= 2:
            raise ForecastEvaluationError(
                "brier_score must be between 0 and 2."
            )

        if loss < 0:
            raise ForecastEvaluationError(
                "log_loss cannot be negative."
            )

        if accuracy not in (0, 1, 0.0, 1.0):
            raise ForecastEvaluationError(
                "directional_accuracy must be 0 or 1."
            )

        brier_scores.append(float(brier))
        log_losses.append(float(loss))
        correct_predictions.append(float(accuracy))

    count = len(records)

    return {
        "status": "SUCCESS",
        "evaluation_count": count,
        "metrics": {
            "mean_brier_score": round(
                sum(brier_scores) / count,
                10,
            ),
            "mean_log_loss": round(
                sum(log_losses) / count,
                10,
            ),
            "directional_accuracy": round(
                sum(correct_predictions) / count,
                10,
            ),
            "correct_predictions": int(
                sum(correct_predictions)
            ),
            "incorrect_predictions": (
                count - int(sum(correct_predictions))
            ),
        },
        "forecast_ids": sorted(seen_forecast_ids),
    }


